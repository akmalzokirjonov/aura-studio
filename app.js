$("#save-brief").addEventListener("click", () => {
  const prompt = $("#creative-prompt").value.trim();
  if (!prompt) {
    setStudioStatus(
      "Add a little direction to your creative brief first.",
      true,
    );
    $("#creative-prompt").focus();
    return;
  }
  const generated = generatedImages.get(currentScene);
  const imageDetails = generated
    ? `Reference image generated by AI Horde.\nModel: ${generated.model}\nSeed: ${generated.seed}\nPrompt used for that image: ${generated.prompt}`
    : "The reference image is a curated preview.";
  const content = `AURA / Creative brief\n\nDirection: ${scenes[currentScene].title}\n\nCurrent brief:\n${prompt}\n\n${imageDetails}\n`;
  const url = URL.createObjectURL(
    new Blob([content], { type: "text/plain;charset=utf-8" }),
  );
  const link = document.createElement("a");
  link.href = url;
  link.download = `aura-${currentScene}-brief.txt`;
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  setStudioStatus("Your creative brief is ready to download.");
});

function setStudioStatus(message, error = false) {
  $("#studio-status").textContent = message;
  $("#studio-status").dataset.error = String(error);
}

function setGenerationBusy(busy) {
  $$(
    "[data-pick], #ai-model, #creative-prompt, #ai-consent, #generate-image",
  ).forEach((control) => {
    control.disabled = busy;
  });
  $("#cancel-generation").hidden = !busy;
  $("#cancel-generation").disabled = false;
  $("#cancel-generation").textContent = "Cancel";
  $("#ai-progress").hidden = !busy;
  $(".studio-output").setAttribute("aria-busy", String(busy));
  $("#generate-image span").textContent = busy ? "Creating…" : "Generate image";
}

function showGenerationProgress(status) {
  let message;
  if (status.phase === "submitting")
    message = "Sending your idea to the free queue…";
  else if (status.phase === "reconnecting")
    message =
      "Waiting for the service to respond. Your request is still active…";
  else if (status.phase === "generating")
    message = "A volunteer GPU is creating your image…";
  else if (status.slow)
    message =
      "The free queue is moving slowly. You can keep waiting or cancel.";
  else {
    message = "Waiting for a volunteer GPU";
    if (status.position !== null)
      message += ` · community queue position ${status.position}`;
    if (status.estimate > 0)
      message += ` · about ${Math.ceil(status.estimate / 60)} min (estimate)`;
  }
  $("#ai-progress-text").textContent = message;
}

$("#generate-image").addEventListener("click", async () => {
  if (activeGeneration) return;
  const prompt = $("#creative-prompt").value.trim();
  if (!prompt) {
    setStudioStatus(
      "Write a description of the image you want to create.",
      true,
    );
    $("#creative-prompt").focus();
    return;
  }
  if (!$("#ai-consent").checked) {
    setStudioStatus(
      "Read and tick the AI Horde sharing agreement before generating.",
      true,
    );
    $("#ai-consent").focus();
    return;
  }
  const operation = { controller: new AbortController(), scene: currentScene };
  activeGeneration = operation;
  setStudioStatus("");
  setGenerationBusy(true);
  try {
    const result = await horde.generateImage({
      prompt,
      model: $("#ai-model").value,
      signal: operation.controller.signal,
      onProgress: showGenerationProgress,
    });
    if (operation.controller.signal.aborted) return;
    const preview = new Image();
    preview.src = result.src;
    try {
      await preview.decode();
    } catch {
      throw new Error(
        "The AI service returned an image the browser could not open. Please try again.",
      );
    }
    if (operation.controller.signal.aborted) return;
    generatedImages.set(operation.scene, result);
    chooseScene(operation.scene);
    setStudioStatus(
      `Image ready · ${result.model}. Download it to keep a copy.`,
    );
  } catch (error) {
    if (error.name === "AbortError") {
      setStudioStatus(
        error.remoteCancelled
          ? "Request cancelled. No new image was saved."
          : "Stopped waiting. The service may still finish a request already in progress.",
      );
    } else {
      setStudioStatus(
        error.message ||
          "The AI service could not create this image. Please try again.",
        true,
      );
    }
  } finally {
    if (activeGeneration === operation) {
      activeGeneration = null;
      setGenerationBusy(false);
    }
  }
});

function cancelGeneration() {
  if (!activeGeneration) return;
  $("#cancel-generation").disabled = true;
  $("#cancel-generation").textContent = "Cancelling…";
  $("#ai-progress-text").textContent = "Cancelling the community request…";
  activeGeneration.controller.abort();
}
