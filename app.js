function openDialog(dialog) {
  lastFocus = document.activeElement;
  closeMenu();
  dialog.showModal();
  document.body.classList.add("modal-open");
}
function closeDialog(dialog) {
  dialog.close();
}
$$("dialog").forEach((dialog) => {
  $("[data-close]", dialog).addEventListener("click", () =>
    closeDialog(dialog),
  );
  dialog.addEventListener("click", (event) => {
    if (event.target !== dialog) return;
    const box = dialog.getBoundingClientRect();
    if (
      event.clientX < box.left ||
      event.clientX > box.right ||
      event.clientY < box.top ||
      event.clientY > box.bottom
    )
      closeDialog(dialog);
  });
  dialog.addEventListener("close", () => {
    document.body.classList.remove("modal-open");
    lastFocus?.focus({ preventScroll: true });
  });
});

function chooseScene(key) {
  drafts.set(currentScene, $("#creative-prompt").value);
  currentScene = key;
  const scene = scenes[key];
  const image = $("#studio-image");
  const generated = generatedImages.get(key);
  image.src = generated?.src ?? scene.image;
  image.alt = generated ? `AI-generated image: ${generated.prompt}` : scene.alt;
  $("#scene-title").textContent = generated
    ? "Your imagination, realized."
    : scene.title;
  $("#image-kind").textContent = generated
    ? `AI · ${generated.model}`
    : "Curated preview";
  $(".studio-output").classList.toggle("generated", Boolean(generated));
  $("#creative-prompt").value = drafts.get(key) ?? scene.prompt;
  const download = $("#download-image");
  download.href = generated?.src ?? scene.image;
  download.download = generated
    ? `aura-${key}-ai.webp`
    : `aura-${key}.${key === "sculpture" ? "png" : "jpg"}`;
  $$("[data-pick]").forEach((button) => {
    const active = button.dataset.pick === key;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  if (!activeGeneration) setStudioStatus("");
}
